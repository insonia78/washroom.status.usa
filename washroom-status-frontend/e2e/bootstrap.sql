-- Historical prerequisites formerly provisioned by imports / the SQL editor.
-- E2E applies the checked-in application schema and every migration afterward.
create schema if not exists extensions;
create extension if not exists postgis with schema extensions;
create table public.restrooms (
 id bigint generated by default as identity primary key,
 osm_type text not null,
 osm_id bigint not null,
 name text,
 latitude double precision not null,
 longitude double precision not null,
 wheelchair text,
 fee text,
 opening_hours text,
 changing_table text,
 unisex text,
 unique(osm_type,osm_id)
);
alter table public.restrooms enable row level security;
revoke all on public.restrooms from public, anon, authenticated;
grant select, insert, update, delete on public.restrooms to service_role;
grant usage, select on sequence public.restrooms_id_seq to service_role;

create table public.export_fuel (
 ogc_fid bigint generated by default as identity primary key,
 "@id" text,
 id text,
 wkb_geometry extensions.geometry(Point,4326),
 amenity text,
 name text,
 brand text,
 operator text,
 toilets text,
 "toilets:access" text,
 "toilets:wheelchair" text,
 "toilets:opening_hours" text,
 "toilets:unisex" text,
 opening_hours text
);
alter table public.export_fuel enable row level security;
revoke all on public.export_fuel from public, anon, authenticated;
grant select on public.export_fuel to service_role;
