begin;

alter table app_locations.toilet_submissions
  add column if not exists map_seq bigint generated by default as identity;

create unique index if not exists toilet_submissions_map_seq_key
  on app_locations.toilet_submissions (map_seq);

-- Community toilets use OSM type "node" with ids far above real OSM ids.
create or replace function app_locations.sync_toilet_to_map()
returns trigger
language plpgsql security definer set search_path = ''
as $$
declare
 v_osm_id bigint := 9000000000000000 + new.map_seq;
begin
 delete from app_locations.restrooms where osm_type = 'node' and osm_id = v_osm_id;
 if new.status = 'approved' and new.archived_at is null then
  insert into app_locations.restrooms
   (osm_type, osm_id, name, latitude, longitude, wheelchair, fee)
  values
   ('node', v_osm_id, new.name, new.latitude, new.longitude, new.wheelchair, new.fee);
 end if;
 return new;
end;
$$;
revoke all on function app_locations.sync_toilet_to_map() from public, anon, authenticated;

drop trigger if exists sync_toilet_to_map on app_locations.toilet_submissions;
create trigger sync_toilet_to_map
  after update of status, archived_at on app_locations.toilet_submissions
  for each row execute function app_locations.sync_toilet_to_map();

-- Backfill toilets that were approved before this migration.
insert into app_locations.restrooms (osm_type, osm_id, name, latitude, longitude, wheelchair, fee)
select 'node', 9000000000000000 + s.map_seq, s.name, s.latitude, s.longitude, s.wheelchair, s.fee
from app_locations.toilet_submissions s
where s.status = 'approved' and s.archived_at is null
  and not exists (
    select 1 from app_locations.restrooms r
    where r.osm_type = 'node' and r.osm_id = 9000000000000000 + s.map_seq
  );

commit;
