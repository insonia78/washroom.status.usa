begin;

create schema if not exists extensions;
create extension if not exists postgis with schema extensions;
set local search_path = pg_catalog, public, extensions;

-- Do not recreate the old public table if it was already moved in place.
do $create$
begin
  if to_regclass('app_locations.supermarkets') is null then
    create table if not exists public.supermarkets (
      id bigint generated by default as identity primary key,
      name text,
      properties jsonb not null default '{}'::jsonb,
      geom geometry(Geometry, 4326) not null
    );

    create index if not exists supermarkets_geom_idx
      on public.supermarkets using gist (geom);

    alter table public.supermarkets enable row level security;
    revoke all on table public.supermarkets from public, anon, authenticated;
    revoke all on sequence public.supermarkets_id_seq from public, anon, authenticated;
    grant select, insert, update, delete on table public.supermarkets to service_role;
    grant usage, select on sequence public.supermarkets_id_seq to service_role;
  end if;
end;
$create$;

commit;
